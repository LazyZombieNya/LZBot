import os
import asyncio
import logging
from typing import Dict, List
from datetime import datetime
from dotenv import load_dotenv

# Инициализируем логгер для вывода критических ошибок конфигурации
logger = logging.getLogger(__name__)

# Загружаем переменные окружения из скрытого файла .env
load_dotenv()

# ==========================================
# КЛЮЧИ И ТОКЕНЫ API
# ==========================================
# Главный токен Telegram-бота
TELEGRAM_TOKEN = os.getenv("TELEGRAM_TOKEN")
if not TELEGRAM_TOKEN:
    logger.critical("ВНИМАНИЕ: TELEGRAM_TOKEN не найден в .env! Бот не сможет запуститься.")

# Ключи для доступа к провайдерам нейросетей
GEMINI_API_KEY = os.getenv("GEMINI_API_KEY")
GROQ_API_KEY = os.getenv("GROQ_API_KEY")
OPENROUTER_API_KEY = os.getenv("OPENROUTER_API_KEY")

# URL-адрес для API Groq (позволяет переопределить адрес, если появится прокси)
GROQ_URL = os.getenv("GROQ_URL", "https://api.groq.com/openai/v1")

# Уникальный Telegram ID владельца бота (для выдачи вечного доступа /zombie_allowed и настроек)
ADMIN_ID = int(os.getenv("ADMIN_ID", 0))

# ==========================================
# СИСТЕМНЫЕ ПРОМПТЫ (ПРАВИЛА ПОВЕДЕНИЯ ИИ)
# ==========================================
# Инструкция для общения в групповых чатах
AI_PROMPT_TGM = os.getenv("AI_PROMPT_TGM", "")
# Инструкция для общения в личных сообщениях (тет-а-тет)
AI_PROMPT_PM = os.getenv("AI_PROMPT_PM", "")
# Дополнительный контекст для групп (как боту понимать имена юзеров)
AI_PROMPT_GM = os.getenv("AI_PROMPT_GM", "")
# Строгий промпт для модели-маршрутизатора, определяющей "Отвечать / Не отвечать" на сообщение
AI_PROMPT_IS_RELEVANT_QUESTION = os.getenv("AI_PROMPT_IS_RELEVANT_QUESTION", "")

# ==========================================
# БАЗОВЫЕ НАСТРОЙКИ БОТА
# ==========================================
# Количество минут, на которое бот умолкает при нажатии кнопки "🔇 Тише"
SILENCE_MINUTES = int(os.getenv("SILENCE_MINUTES", "10"))

# Имена файлов для хранения истории и списка моделей
DB_PATH = "chat_history.db"
MODELS_CONFIG_PATH = "models.json"

# Жесткий лимит Telegram API: одно сообщение не может быть длиннее 4096 символов.
# Если ответ ИИ длиннее, мы дробим его на части с помощью функции split_message().
MAX_MESSAGE_LENGTH = 4096

# Защита от спама (Троттлинг): минимальное время между запросами от одного юзера/группы (в секундах)
RATE_LIMIT_SECONDS_PER_USER = 1.0

# ==========================================
# ГЛОБАЛЬНАЯ ПАМЯТЬ БОТА (SHARED STATE)
# ==========================================
# Эти переменные живут только в оперативной памяти (RAM) и сбрасываются при перезапуске скрипта.

# Глобальный семафор для ИИ. Цифра 1 означает, что бот делает строго 1 запрос
# к API нейросетей одновременно, а остальные ждут в очереди.
# Это защищает от ошибки 429 (Слишком много запросов).
GLOBAL_SEMAPHORE = asyncio.Semaphore(1)

# Блокировщики чатов. Если пользователь задал вопрос и бот уже генерирует ответ,
# Lock() не даст пользователю запустить генерацию второго ответа параллельно.
user_locks: Dict[int, asyncio.Lock] = {}

# Буфер для склеивания быстрых сообщений. Если юзер пришлет пересылку,
# а через полсекунды допишет текст, буфер поймает оба сообщения и объединит их.
user_buffers: Dict[int, list] = {}

# Реестр активных процессов генерации ответа. Используется, чтобы прервать
# генерацию, если юзер нажмет кнопку "🛑 Отмена".
active_tasks: Dict[int, asyncio.Task] = {}

# Реестр времени последних обращений (нужен для работы RATE_LIMIT_SECONDS_PER_USER)
last_request_time: Dict[int, datetime] = {}

# Реестр "заглушенных" чатов. Если chat_id есть в этом списке,
# бот игнорирует всё, кроме прямых упоминаний, пока не истечет указанное время.
silenced_chats: Dict[int, datetime] = {}